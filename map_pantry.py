def norm(s):
    s = s.lower()
    s = re.sub(r"\*+", "", s)
    s = re.sub(r"[^a-z ]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def is_header(slug, name):
    """True if this line is a source group label, not an ingredient."""
    n = norm(name)
    if not n:
        return True
    if n in HEADERS:
        return True
    if len(n) <= 3 and not n.isdigit():
        return True
    # the dish's own name, where the source lists it as a group label
    if n in ("kåldolmar", "lobster tails", "crème fraîche, about 1 tablespoon per rose",
             "crème fraîche"):
        return True
    # "1806 version" / "1895 version" style
    if re.match(r"^\d{4}\s+version$", n):
        return True
    # a line that is only a plural noun with no quantity and no verb
    return False


def key_for(slug, name, note):
    raw = name.strip()
    # exact override by (slug, name)
    if (slug, raw) in OVERRIDES:
        return OVERRIDES[(slug, raw)]
    # override by name alone (case-insensitive)
    n = norm(raw)
    for (sl, nm), k in OVERRIDES.items():
        if sl == slug and norm(nm) == n:
            return k
    # non-ascii-safe substring checks, before the regex rules
    if "kåldolmar" in n:
        return "misc"
    if "lobster" in n:
        return "fish"
    if "crème" in n or "creme fraiche" in n:
        return "cream"
    for rx, key in RULES:
        if re.search(rx, n):
            return key
    for rx, key in EXTRA_RULES:
        if re.search(rx, n):
            return key
    # try the note too
    if note:
        for rx, key in RULES + EXTRA_RULES:
            if re.search(rx, norm(note)):
                return key
    return ""


# ---------------------------------------------------------------- run
gen = []
unmapped = {}
skipped = []
for rec in EXTRACTED:
    slug = rec["slug"]
    ings = []
    for ing in rec["ingredients"]:
        # drop source group labels
        if is_header(slug, ing["name"]):
            continue
        key = key_for(slug, ing["name"], ing.get("note", ""))
        if not key:
            unmapped.setdefault(slug, []).append(ing["name"])
            key = "misc"
        ings.append({
            "name": ing["name"],
            "qty": ing["qty"],
            "unit": ing["unit"],
            "pantry": key,
            "note": ing.get("note", ""),
        })
    if len(ings) < 3:
        skipped.append(slug)
        continue
    gen.append({
        "id": "th-" + slug,
        "title": rec["title"],
        "era": rec["era"],
        "year": rec["year"],
        "region": rec["region"],
        "source": rec["source"],
        "source_url": rec["source_url"],
        "servings": 4,
        "tags": [],
        "confidence": "likely",
        "history": rec["history"],
        "source_text": "",
        "method": rec["method"],
        "ingredients": ings,
        "funky": [],
        # Tasting History prints an ingredient list, but the quantities are
        # the author's own modern ones rather than the source's.
        "ingredient_source": "sourced",
    })

